struct FPackageFileVersion {
    std::int32_t fileVersionUE4 = 0;
    std::int32_t fileVersionUE5 = 0;

    constexpr auto operator<=>(EUnrealEngineObjectUE4Version version) const { return fileVersionUE4 <=> static_cast<std::int32_t>(version); }
    constexpr auto operator<=>(EUnrealEngineObjectUE5Version version) const { return fileVersionUE5 <=> static_cast<std::int32_t>(version); }
    constexpr bool operator==(EUnrealEngineObjectUE4Version version) const { return fileVersionUE4 == static_cast<std::int32_t>(version); }
    constexpr bool operator==(EUnrealEngineObjectUE5Version version) const { return fileVersionUE5 == static_cast<std::int32_t>(version); }
    constexpr bool operator==(const FPackageFileVersion&) const = default;
};

constexpr FPackageFileVersion getEnginePackageFileVersion(const EGame game) {
    constexpr std::int32_t latestUE4 = static_cast<std::int32_t>(EUnrealEngineObjectUE4Version::AUTOMATIC_VERSION);
    if (game >= EGame::GAME_UE5_0) {
        using V = EUnrealEngineObjectUE5Version;
        const auto ue5 = [](V version) { return FPackageFileVersion{latestUE4, static_cast<std::int32_t>(version)}; };
        if (game < EGame::GAME_UE5_1)
            return ue5(V::LARGE_WORLD_COORDINATES);
        if (game < EGame::GAME_UE5_2)
            return ue5(V::ADD_SOFTOBJECTPATH_LIST);
        if (game < EGame::GAME_UE5_4)
            return ue5(V::DATA_RESOURCES);
        if (game < EGame::GAME_UE5_5)
            return ue5(V::PROPERTY_TAG_COMPLETE_TYPE_NAME);
        if (game < EGame::GAME_UE5_6)
            return ue5(V::ASSETREGISTRY_PACKAGEBUILDDEPENDENCIES);
        if (game < EGame::GAME_UE5_7)
            return ue5(V::OS_SUB_OBJECT_SHADOW_SERIALIZATION);
        return ue5(V::AUTOMATIC_VERSION);
    }
    constexpr std::array<std::int32_t, 27> ue4VersionOfMinor{342, 352, 363, 382, 385, 401, 413, 434, 451, 482, 482, 498, 504, 505,
                                                             508, 510, 513, 513, 514, 516, 516, 517, 517, 517, 518, 518, 522};
    const std::uint32_t minor = (static_cast<std::uint32_t>(game) - static_cast<std::uint32_t>(EGame::GAME_UE4_0)) >> 16;
    if (minor < ue4VersionOfMinor.size())
        return FPackageFileVersion{ue4VersionOfMinor[minor], 0};
    return FPackageFileVersion{latestUE4, 0};
}

