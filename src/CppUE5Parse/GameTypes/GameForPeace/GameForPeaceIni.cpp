namespace ue5parse {

namespace {

constexpr std::uint64_t gameForPeaceIniMagic = 0x4B4457585D5D5B7D;

//! The nine rotations of "123456789".
constexpr std::array<std::uint8_t, 81> gameForPeaceIniKey = {
    0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39,
    0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x31,
    0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x31, 0x32,
    0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x31, 0x32, 0x33,
    0x35, 0x36, 0x37, 0x38, 0x39, 0x31, 0x32, 0x33, 0x34,
    0x36, 0x37, 0x38, 0x39, 0x31, 0x32, 0x33, 0x34, 0x35,
    0x37, 0x38, 0x39, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36,
    0x38, 0x39, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37,
    0x39, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38,
};

}

void decryptGameForPeaceIni(std::span<std::byte> file) {
    std::uint64_t start = 0;
    if (file.size() < sizeof(start))
        return;
    std::memcpy(&start, file.data(), sizeof(start));
    if (start != gameForPeaceIniMagic)
        return;
    for (std::size_t i = 0; i < file.size(); i++)
        file[i] ^= static_cast<std::byte>(gameForPeaceIniKey[i % gameForPeaceIniKey.size()]);
}

}
