//! Follows the CUE4Parse Lua reader: it decrypts the strings and code of a Lua 5.4 dump in place and writes the true header values back.
class LuaDecryptor {
public:
    explicit LuaDecryptor(std::span<std::byte> file) : file(file) {}

    Result<void> run() {
        constexpr std::array<std::uint8_t, 4> signature = {0x1B, 'L', 'u', 'a'};
        constexpr std::array<std::uint8_t, 6> data = {0x19, 0x93, 0x0D, 0x0A, 0x1A, 0x0A};
        constexpr std::array<std::uint8_t, 8> integer = {0x78, 0x56, 0, 0, 0, 0, 0, 0};
        constexpr double number = 370.5;
        write(signature);
        write(std::array<std::uint8_t, 1>{0x54});
        decryptBlock(1);
        write(data);
        for (int i = 0; i < 3; i++)
            decryptBlock(1);
        write(integer);
        std::array<std::uint8_t, 8> numberBytes{};
        std::memcpy(numberBytes.data(), &number, sizeof(number));
        write(numberBytes);
        decryptBlock(1);
        processFunction(0);
        if (failed)
            return fail(ErrorCode::InvalidData, "decryptArenaBreakoutInfiniteLua", position);
        return {};
    }

private:
    template <std::size_t N>
    void write(const std::array<std::uint8_t, N>& bytes) {
        if (position + N > file.size()) {
            failed = true;
            return;
        }
        std::memcpy(file.data() + position, bytes.data(), N);
        position += N;
    }

    void decryptBlock(std::uint64_t length) {
        if (failed || length > file.size() - position) {
            failed = true;
            return;
        }
        auto previous = static_cast<std::uint8_t>(luaKey[0]);
        for (std::size_t i = 0; i < length; i++) {
            auto plain = static_cast<std::uint8_t>(static_cast<std::uint8_t>(file[position + i]) ^ (static_cast<std::uint8_t>(luaKey[i % luaKey.size()]) | previous));
            file[position + i] = static_cast<std::byte>(plain);
            previous = plain;
        }
        position += static_cast<std::size_t>(length);
    }

    std::uint8_t readByte() {
        if (failed || position >= file.size()) {
            failed = true;
            return 0;
        }
        auto value = static_cast<std::uint8_t>(static_cast<std::uint8_t>(file[position]) ^ static_cast<std::uint8_t>(luaKey[0]));
        file[position++] = static_cast<std::byte>(value);
        return value;
    }

    std::uint64_t readSize() {
        std::uint64_t value = 0;
        for (int count = 0; count < 16; count++) {
            if (failed || position >= file.size()) {
                failed = true;
                return 0;
            }
            auto stored = static_cast<std::uint8_t>(file[position++]);
            value = (value << 7) | (stored & 0x7F);
            if ((stored & 0x80) != 0)
                return value;
        }
        failed = true;
        return 0;
    }

    void decryptString() {
        std::uint64_t sizePlusOne = readSize();
        if (sizePlusOne != 0)
            decryptBlock(sizePlusOne - 1);
    }

    void processFunction(int depth) {
        if (depth > 200) {
            failed = true;
            return;
        }
        decryptString();
        readSize();
        readSize();
        for (int i = 0; i < 3; i++)
            decryptBlock(1);
        std::uint64_t codeCount = readSize();
        if (codeCount > file.size()) {
            failed = true;
            return;
        }
        std::size_t codeStart = position;
        decryptBlock(codeCount * 4);
        for (std::uint64_t i = 0; i < codeCount && !failed; i++) {
            std::byte& opcode = file[codeStart + static_cast<std::size_t>(i) * 4];
            std::uint8_t stored = static_cast<std::uint8_t>(opcode) & 0x7F;
            if (stored >= opcodeMapping.size()) {
                failed = true;
                return;
            }
            opcode = static_cast<std::byte>((static_cast<std::uint8_t>(opcode) & 0x80) | opcodeMapping[stored]);
        }
        std::uint64_t constantCount = readSize();
        for (std::uint64_t i = 0; i < constantCount && !failed; i++) {
            std::uint8_t type = readByte();
            if (type == 3 || type == 19)
                decryptBlock(8);
            else if (type == 4 || type == 20)
                decryptString();
        }
        std::uint64_t upvalueCount = readSize();
        for (std::uint64_t i = 0; i < upvalueCount && !failed; i++)
            for (int j = 0; j < 3; j++)
                readByte();
        std::uint64_t functionCount = readSize();
        for (std::uint64_t i = 0; i < functionCount && !failed; i++)
            processFunction(depth + 1);
        processDebug();
    }

    void processDebug() {
        decryptBlock(readSize());
        std::uint64_t absoluteLines = readSize();
        for (std::uint64_t i = 0; i < absoluteLines && !failed; i++) {
            readSize();
            readSize();
        }
        std::uint64_t locals = readSize();
        for (std::uint64_t i = 0; i < locals && !failed; i++) {
            decryptString();
            readSize();
            readSize();
        }
        std::uint64_t upvalues = readSize();
        for (std::uint64_t i = 0; i < upvalues && !failed; i++)
            decryptString();
    }

    std::span<std::byte> file;
    std::size_t position = 0;
    bool failed = false;
};

