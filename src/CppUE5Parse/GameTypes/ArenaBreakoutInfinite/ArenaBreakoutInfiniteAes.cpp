//! The game picks each SM4 key byte from a table by the low six bits of the given key byte.
void decryptSm4(std::span<std::byte> data, std::span<const std::byte, 16> key, const KeyTable& table, const Sm4::Sbox& sbox) {
    std::array<std::byte, 16> mapped{};
    for (std::size_t i = 0; i < mapped.size(); i++)
        mapped[i] = static_cast<std::byte>(table[static_cast<std::uint8_t>(key[i]) & 0x3F]);
    Sm4::decrypt(data, Sm4::expandKey(mapped, sbox, familyKey, constantKey), sbox);
}

std::span<const std::byte, 16> asKey(const std::array<std::uint8_t, 16>& key) {
    return std::as_bytes(std::span<const std::uint8_t, 16>(key));
}

bool endsWithIgnoreCase(std::string_view text, std::string_view suffix) {
    if (text.size() < suffix.size())
        return false;
    for (std::size_t i = 0; i < suffix.size(); i++) {
        char c = text[text.size() - suffix.size() + i];
        if ((c >= 'A' && c <= 'Z' ? static_cast<char>(c - 'A' + 'a') : c) != suffix[i])
            return false;
    }
    return true;
}

